package org.cortex.terminal.runtime

import android.util.Log
import java.io.File

/**
 * Owns the user's shell startup files so that they behave exactly like on a stock
 * Ubuntu 24.04 install:
 *
 *  - `~/.profile` and `~/.bashrc` are plain user files. They are created once from
 *    `/etc/skel` (Ubuntu's own defaults) and are never rewritten afterwards, so whatever
 *    an installer (nvm, bun, rustup, opencode, ...) appends there is kept.
 *  - Everything Cortex itself needs lives in `/etc/profile.d` (see
 *    [BootstrapManager.ensureProfileEnvironment]), which the app owns and regenerates.
 *
 * Releases up to 1.25.26 instead rewrote both files on every app start. That raced with
 * installers and even deleted the `.opencode/bin` PATH line the opencode installer had
 * written. [migrateLegacyStartupFile] removes only what those releases injected.
 */
object ShellProfile {
    private const val TAG = "ShellProfile"

    private const val D = "$"

    /** Marks a file as having been generated by a Cortex release up to 1.25.26. */
    private val LEGACY_MARKERS = listOf(
        "_CORTEX_PROF_GUARD",
        "_CORTEX_RC_GUARD",
        "# Cortex Terminal Environment"
    )

    private val LEGACY_CERT_SNIPPET =
        "if [ -z \"${D}CORTEX_ROOT\" ]; then\n" +
        "    if [ -d \"${D}HOME/../etc\" ]; then\n" +
        "        export CORTEX_ROOT=\"$(cd \"${D}HOME/..\" && pwd)\"\n" +
        "    fi\n" +
        "fi\n" +
        "if [ -n \"${D}CORTEX_ROOT\" ]; then\n" +
        "    export SSL_CERT_FILE=\"${D}CORTEX_ROOT/etc/ssl/certs/ca-certificates.crt\"\n" +
        "    export SSL_CERT_DIR=\"${D}CORTEX_ROOT/etc/ssl/certs:/system/etc/security/cacerts\"\n" +
        "    export CURL_CA_BUNDLE=\"${D}CORTEX_ROOT/etc/ssl/certs/ca-certificates.crt\"\n" +
        "    export NODE_EXTRA_CA_CERTS=\"${D}CORTEX_ROOT/etc/ssl/certs/ca-certificates.crt\"\n" +
        "    export REQUESTS_CA_BUNDLE=\"${D}CORTEX_ROOT/etc/ssl/certs/ca-certificates.crt\"\n" +
        "else\n" +
        "    export SSL_CERT_FILE=/etc/ssl/certs/ca-certificates.crt\n" +
        "    export CURL_CA_BUNDLE=/etc/ssl/certs/ca-certificates.crt\n" +
        "fi\n"

    private val LEGACY_PS1_BLOCK =
        "if [ -n \"${D}BASH_VERSION\" ]; then\n" +
        "    export PS1='\\w ${D} '\n" +
        "else\n" +
        "    export PS1='~ ${D} '\n" +
        "fi\n"

    private val LEGACY_TZDIR_BLOCK =
        "if [ -d \"${D}HOME/../usr/share/zoneinfo\" ]; then\n" +
        "    export TZDIR=\"${D}HOME/../usr/share/zoneinfo\"\n" +
        "elif [ -d \"/usr/share/zoneinfo\" ]; then\n" +
        "    export TZDIR=\"/usr/share/zoneinfo\"\n" +
        "fi\n"

    private val LEGACY_TZ_LINE =
        "if [ -f /etc/timezone ]; then export TZ=\"$(cat /etc/timezone 2>/dev/null)\"; fi\n"

    private val LEGACY_RELOAD_FN =
        "reload() {\n" +
        "    set --\n" +
        "    if [ -f \"${D}HOME/.bashrc\" ]; then . \"${D}HOME/.bashrc\"; fi\n" +
        "    if [ -f \"${D}HOME/.profile\" ]; then . \"${D}HOME/.profile\"; fi\n" +
        "    if [ -f \"${D}HOME/.bash_profile\" ]; then . \"${D}HOME/.bash_profile\"; fi\n" +
        "    echo \"Configuration reloaded successfully.\"\n" +
        "}\n" +
        "alias reload='reload'\n"

    private val LEGACY_PROF_GUARD_BLOCK = Regex(
        "(?m)^if \\[ -f \"${Regex.escape(D)}HOME/\\.profile\" \\] && \\[ -z \"${Regex.escape(D)}_CORTEX_PROF_GUARD\" \\]; then\\n" +
            "    _CORTEX_PROF_GUARD=1\\n" +
            "    \\. \"${Regex.escape(D)}HOME/\\.profile\"\\n" +
            "    unset _CORTEX_PROF_GUARD\\n" +
            "fi\\n?"
    )

    private val LEGACY_RC_GUARD_BLOCK = Regex(
        "(?m)^if \\[ -f \"${Regex.escape(D)}HOME/\\.bashrc\" \\] && \\[ -z \"${Regex.escape(D)}_CORTEX_RC_GUARD\" \\]; then\\n" +
            "    _CORTEX_RC_GUARD=1\\n" +
            "    \\. \"${Regex.escape(D)}HOME/\\.bashrc\"\\n" +
            "    unset _CORTEX_RC_GUARD\\n" +
            "fi\\n?"
    )

    private val LEGACY_AUTOSTART_BLOCK = Regex(
        "(?m)^if \\[ -d /etc/cortex/autostart \\]; then\\n" +
            "    for s in /etc/cortex/autostart/\\*; do\\n" +
            "        if \\[ -f \"${Regex.escape(D)}s\" \\]; then\\n" +
            "            sname=\"${Regex.escape(D)}\\(basename \"${Regex.escape(D)}s\"\\)\"\\n" +
            "            service \"${Regex.escape(D)}sname\" start >/dev/null 2>&1 \\|\\| true\\n" +
            "        fi\\n" +
            "    done\\n" +
            "fi\\n?"
    )

    /**
     * Earlier releases stripped `/home/.opencode/bin:` out of `.bashrc`. The opencode
     * installer writes its absolute PATH (`.../files/cortex/home/.opencode/bin`), so the
     * strip cut the line to `export PATH=.../files/cortex$PATH`. Put the directory back.
     */
    private val CORRUPTED_OPENCODE_PATH = Regex(
        "(?m)^export PATH=(/[^\\s:\$]*/files/cortex)${Regex.escape(D)}PATH[ \\t]*$"
    )

    /** The `$HOME/.opencode/bin:` variant of the same strip leaves a no-op `export PATH=$PATH`. */
    private val NOOP_OPENCODE_PATH = Regex("(?m)^(# opencode\\n)export PATH=${Regex.escape(D)}PATH[ \\t]*$")

    /** What Ubuntu 24.04 ships in /etc/skel/.profile. */
    internal val DEFAULT_PROFILE = """
        # ~/.profile: executed by the command interpreter for login shells.
        # This file is not read by bash(1), if ~/.bash_profile or ~/.bash_login
        # exists.
        # see /usr/share/doc/bash/examples/startup-files for examples.
        # the files are located in the bash-doc package.

        # the default umask is set in /etc/profile; for setting the umask
        # for ssh logins, install and configure the libpam-umask package.
        #umask 022

        # if running bash
        if [ -n "${D}BASH_VERSION" ]; then
            # include .bashrc if it exists
            if [ -f "${D}HOME/.bashrc" ]; then
                . "${D}HOME/.bashrc"
            fi
        fi

        # set PATH so it includes user's private bin if it exists
        if [ -d "${D}HOME/bin" ] ; then
            PATH="${D}HOME/bin:${D}PATH"
        fi

        # set PATH so it includes user's private bin if it exists
        if [ -d "${D}HOME/.local/bin" ] ; then
            PATH="${D}HOME/.local/bin:${D}PATH"
        fi
    """.trimIndent() + "\n"

    /** Condensed version of Ubuntu 24.04's /etc/skel/.bashrc, used only if /etc/skel is missing. */
    internal val DEFAULT_BASHRC = """
        # ~/.bashrc: executed by bash(1) for non-login shells.
        # see /usr/share/doc/bash/examples/startup-files (in the package bash-doc)
        # for examples

        # If not running interactively, don't do anything
        case ${D}- in
            *i*) ;;
              *) return;;
        esac

        # don't put duplicate lines or lines starting with space in the history.
        # See bash(1) for more options
        HISTCONTROL=ignoreboth

        # append to the history file, don't overwrite it
        shopt -s histappend

        # for setting history length see HISTSIZE and HISTFILESIZE in bash(1)
        HISTSIZE=1000
        HISTFILESIZE=2000

        # check the window size after each command and, if necessary,
        # update the values of LINES and COLUMNS.
        shopt -s checkwinsize

        # make less more friendly for non-text input files, see lesspipe(1)
        [ -x /usr/bin/lesspipe ] && eval "${D}(SHELL=/bin/sh lesspipe)"

        # set variable identifying the chroot you work in (used in the prompt below)
        if [ -z "${D}{debian_chroot:-}" ] && [ -r /etc/debian_chroot ]; then
            debian_chroot=${D}(cat /etc/debian_chroot)
        fi

        # enable color support of ls and also add handy aliases
        if [ -x /usr/bin/dircolors ]; then
            test -r ~/.dircolors && eval "${D}(dircolors -b ~/.dircolors)" || eval "${D}(dircolors -b)"
            alias ls='ls --color=auto'
            alias grep='grep --color=auto'
            alias fgrep='fgrep --color=auto'
            alias egrep='egrep --color=auto'
        fi

        # some more ls aliases
        alias ll='ls -alF'
        alias la='ls -A'
        alias l='ls -CF'

        # Alias definitions.
        # You may want to put all your additions into a separate file like
        # ~/.bash_aliases, instead of adding them here directly.
        if [ -f ~/.bash_aliases ]; then
            . ~/.bash_aliases
        fi

        # enable programmable completion features (you don't need to enable
        # this, if it's already enabled in /etc/bash.bashrc and /etc/profile
        # sources /etc/bash.bashrc).
        if ! shopt -oq posix; then
          if [ -f /usr/share/bash-completion/bash_completion ]; then
            . /usr/share/bash-completion/bash_completion
          elif [ -f /etc/bash_completion ]; then
            . /etc/bash_completion
          fi
        fi
    """.trimIndent() + "\n"

    /** Keeps the compact Cortex prompt of earlier releases; delete the line for Ubuntu's stock prompt. */
    internal val CORTEX_PROMPT_LINE =
        "\n# Cortex keeps its compact prompt; delete this line to get Ubuntu's user@host:dir prompt.\n" +
            "PS1='\\w ${D} '\n"

    /**
     * Creates `~/.profile` and `~/.bashrc` if they do not exist and cleans up what releases
     * up to 1.25.26 injected into existing ones. Files that need no migration are not touched.
     *
     * @param skel `/etc/skel` of the rootfs (Ubuntu's default dotfiles), or null.
     * @param rootfsReady false while the Ubuntu base system has not been extracted yet; missing
     *   files are then left alone and created by the next call.
     */
    fun ensureUserStartupFiles(home: File, skel: File?, rootfsReady: Boolean = true) {
        home.mkdirs()
        ensureFile(File(home, ".profile"), skel?.let { File(it, ".profile") }, DEFAULT_PROFILE, "", rootfsReady)
        ensureFile(File(home, ".bashrc"), skel?.let { File(it, ".bashrc") }, DEFAULT_BASHRC, CORTEX_PROMPT_LINE, rootfsReady)
        removeLegacyHelperScripts(File(home, ".local/bin"))
    }

    private fun ensureFile(target: File, skelFile: File?, fallback: String, suffix: String, rootfsReady: Boolean) {
        try {
            if (!target.exists()) {
                if (!rootfsReady) return
                val base = skelFile?.takeIf { it.isFile && it.length() > 0 }?.let {
                    try { it.readText() } catch (_: Exception) { null }
                } ?: fallback
                writeAtomically(target, base.trimEnd() + "\n" + suffix)
                return
            }
            if (!target.isFile) return
            val current = target.readText()
            val migrated = migrateLegacyStartupFile(current, target.name == ".profile")
            if (migrated != current) {
                writeAtomically(target, migrated)
                Log.i(TAG, "Migrated legacy Cortex startup content in ${target.name}")
            }
        } catch (e: Exception) {
            Log.e(TAG, "Failed to ensure ${target.name}", e)
        }
    }

    /**
     * Removes the blocks Cortex releases up to 1.25.26 injected on every start, keeping every
     * line the user or an installer added. Idempotent; text without legacy markers (and without
     * the corrupted opencode PATH line) is returned unchanged.
     */
    fun migrateLegacyStartupFile(text: String, isProfile: Boolean): String {
        var out = text
        val hasLegacy = LEGACY_MARKERS.any { out.contains(it) }
        if (hasLegacy) {
            out = out.replace(LEGACY_RELOAD_FN, "")
            out = LEGACY_PROF_GUARD_BLOCK.replace(out, "")
            out = LEGACY_AUTOSTART_BLOCK.replace(out, "")
            out = out.replace("# Cortex Terminal Environment\n", "")
            out = out.replace(LEGACY_PS1_BLOCK, "")
            out = out.replace(LEGACY_CERT_SNIPPET, "")
            out = out.replace(LEGACY_TZDIR_BLOCK, "")
            out = out.replace(LEGACY_TZ_LINE, "")
            for (line in listOf("unset PREFIX", "shopt -s checkwinsize 2>/dev/null", "export GODEBUG=netdns=cgo")) {
                out = out.replace(Regex("(?m)^" + Regex.escape(line) + "[ \\t]*\\n?"), "")
            }
            // ~/.profile has to hand over to ~/.bashrc like Ubuntu's own does.
            out = LEGACY_RC_GUARD_BLOCK.replace(out) {
                "# if running bash\n" +
                    "if [ -n \"${D}BASH_VERSION\" ]; then\n" +
                    "    # include .bashrc if it exists\n" +
                    "    if [ -f \"${D}HOME/.bashrc\" ]; then\n" +
                    "        . \"${D}HOME/.bashrc\"\n" +
                    "    fi\n" +
                    "fi\n"
            }
            out = out.replace(Regex("\\n{3,}"), "\n\n")
            if (!isProfile) out = out.trimStart('\n')
        }
        out = CORRUPTED_OPENCODE_PATH.replace(out) {
            "export PATH=${it.groupValues[1]}/home/.opencode/bin:${D}PATH"
        }
        out = NOOP_OPENCODE_PATH.replace(out) {
            it.groupValues[1] + "export PATH=\"${D}HOME/.opencode/bin:${D}PATH\""
        }
        if (out != text) out = out.trimEnd() + "\n"
        return out
    }

    /** `~/.local/bin/bashrc` and `~/.local/bin/profile` were helper scripts of the old scheme. */
    private fun removeLegacyHelperScripts(localBin: File) {
        for (name in listOf("bashrc", "profile")) {
            try {
                val f = File(localBin, name)
                if (f.isFile && f.length() < 1024) {
                    val t = f.readText()
                    if (t.startsWith("#!/bin/bash\nif (return 0 2>/dev/null); then\n") &&
                        t.contains("exec \"${D}{SHELL:-/bin/bash}\" -l")
                    ) {
                        f.delete()
                    }
                }
            } catch (_: Exception) {
            }
        }
    }

    private fun writeAtomically(target: File, content: String) {
        val tmp = File(target.parentFile, "${target.name}.cortex-tmp")
        tmp.writeText(content)
        try { android.system.Os.chmod(tmp.absolutePath, 384) } catch (_: Throwable) {} // 0600
        if (!tmp.renameTo(target)) {
            target.writeText(content)
            tmp.delete()
        }
    }
}
